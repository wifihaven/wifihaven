-- render.lua — generates dnsmasq and nftables config from a policy snapshot
--
-- Snapshot field naming: the API serializes PolicySnapshot/PolicyProfile/
-- PolicyDevice via zio-json deriveCodec, which keeps the Scala case-class
-- field names verbatim (camelCase) — see shared/src/Models.scala. This module
-- reads those keys (profileId, extraBlocked, siteLimits, dailyMinutes,
-- timeUsedToday.totalMinutes, extensionsTodayMinutes) directly. If the API's
-- JSON casing ever changes, change it here too (and update render_spec.lua).
--
-- Public API:
--   render.dnsmasq(snapshot)  → string  (/tmp/dnsmasq.d/familydns.conf content)
--   render.nft(snapshot)      → string  (/tmp/nftables.d/familydns.nft content)
--   render.update_shared(snapshot, nft_sets, blocked_macs, blocked_reason)
--     Seeds the shared tables that conntrack.lua uses for hostname attribution
--     and for labeling per-MAC blocked flows (pause / time-exhausted).
--
-- Counter naming convention (used by usage.lua):
--   ct_<mac_underscored>__<dst_ip_underscored>
--   e.g.  aa:bb:cc:11:22:33 + 1.2.3.4  →  ct_aa_bb_cc_11_22_33__1_2_3_4
--   The double-underscore (__) separates MAC from IP unambiguously.

local M = {}

-- Replace dots and colons with underscores (nftables set/counter name-safe).
local function sanitize(s)
  return (s:gsub("[%.%:]", "_"))
end
M.sanitize = sanitize

-- ---------------------------------------------------------------------------
-- render.dnsmasq(snapshot) → string
-- ---------------------------------------------------------------------------
function M.dnsmasq(snapshot)
  local out = {}
  local function emit(s) out[#out + 1] = s end

  emit("# familydns — generated by render.lua, do not edit")
  emit("")

  -- #259: query logging is enabled via UCI (`option logqueries '1'`,
  -- `option logfacility '/tmp/familydns-dnsmasq.log'`) so OpenWRT's dnsmasq
  -- init script knows to bind-mount the log file RW into dnsmasq's ujail.
  -- Emitting it here too would trip dnsmasq's "illegal repeated keyword"
  -- check (#287).

  -- MAC → profile tag so dnsmasq can apply per-profile rules.
  -- Devices auto-created from first_seen_mac events have profileId=nil
  -- until an admin assigns them; skip them (no policy to apply yet).
  emit("# device MAC → profile tag")
  for _, dev in ipairs(snapshot.devices or {}) do
    if dev.profileId then
      emit(string.format("dhcp-host=%s,set:profile%d", dev.mac, dev.profileId))
    end
  end
  emit("")

  -- extraBlocked → NXDOMAIN; deduplicate domains that appear in multiple profiles
  emit("# extraBlocked → NXDOMAIN")
  local seen_blocked = {}
  for _, prof in ipairs(snapshot.profiles or {}) do
    for _, domain in ipairs(prof.extraBlocked or {}) do
      if not seen_blocked[domain] then
        seen_blocked[domain] = true
        emit("address=/" .. domain .. "/#")
      end
    end
  end
  emit("")

  -- siteLimits → ipset= so dnsmasq populates nftables sets with resolved IPs
  emit("# siteLimits → nftables ipset population for usage accounting")
  for _, prof in ipairs(snapshot.profiles or {}) do
    for _, sl in ipairs(prof.siteLimits or {}) do
      local set_name = string.format("profile%d_%s", prof.id, sanitize(sl.domain))
      emit(string.format("ipset=/%s/%s", sl.domain, set_name))
    end
  end
  emit("")

  return table.concat(out, "\n")
end

-- ---------------------------------------------------------------------------
-- render.nft(snapshot, opts) → string
-- ---------------------------------------------------------------------------
-- opts (optional table):
--   poll_age_seconds  number — seconds since the last successful policy poll.
--                              When > 300 (the #269 §4 threshold), profiles
--                              with failureMode == "closed" get an additional
--                              failover drop rule for ALL their devices'
--                              MACs. failureMode == "open" profiles are
--                              unaffected (cached snapshot keeps enforcing).
--                              When nil or <= 300, no failover output.
--
-- TODO(#323): the agent main loop must compute poll_age and pass it here once
-- #309 lands last_successful_poll_ts. Until then nothing populates opts, so
-- this branch is dormant in production — but the field is in the snapshot
-- and the rendering logic is tested, so flipping it on is a one-liner.
function M.nft(snapshot, opts)
  local out = {}
  local function emit(s)  out[#out + 1] = s  end
  local function ind(s)   out[#out + 1] = "  " .. s  end
  local function ind2(s)  out[#out + 1] = "    " .. s end

  emit("# familydns — generated by render.lua, do not edit")
  emit("# Load with a single `nft -f <this file>`. The prelude below performs an")
  emit("# atomic handover from the boot default-deny skeleton (table inet")
  emit("# familydns_boot, installed by /etc/init.d/familydns-boot — see #308) to")
  emit("# the runtime table in one transaction, so there is no zero-second leak")
  emit("# window. `add table X; delete table X` is idempotent: works whether or")
  emit("# not the table currently exists.")
  emit("add table inet familydns_boot")
  emit("delete table inet familydns_boot")
  emit("add table inet familydns")
  emit("delete table inet familydns")
  emit("table inet familydns {")
  emit("")

  -- Build profileId → [macs] index. Skip unassigned devices (profileId=nil);
  -- they have no profile to be matched against in the nft sets.
  local profile_macs = {}
  for _, dev in ipairs(snapshot.devices or {}) do
    local pid = dev.profileId
    if pid then
      if not profile_macs[pid] then profile_macs[pid] = {} end
      profile_macs[pid][#profile_macs[pid] + 1] = dev.mac
    end
  end

  -- Per-profile MAC sets
  for _, prof in ipairs(snapshot.profiles or {}) do
    local macs = profile_macs[prof.id] or {}
    ind(string.format("set profile%d_macs {", prof.id))
    ind2("type ether_addr")
    if #macs > 0 then
      ind2("elements = { " .. table.concat(macs, ", ") .. " }")
    end
    ind("}")
    emit("")
  end

  -- Per-domain IP sets for siteLimits (dynamic: populated by dnsmasq --ipset= at query time)
  for _, prof in ipairs(snapshot.profiles or {}) do
    for _, sl in ipairs(prof.siteLimits or {}) do
      local set_name = string.format("profile%d_%s", prof.id, sanitize(sl.domain))
      ind(string.format("set %s {", set_name))
      ind2("type ipv4_addr")
      ind2("flags dynamic,timeout")
      ind2("timeout 1h")
      ind("}")
      emit("")
    end
  end

  -- Per-flow accounting set (conntrack.lua adds rules referencing named counters;
  -- this set is also used as a fallback for byte accounting via dynamic population)
  ind("set mac_ip_tracking {")
  ind2("type ether_addr . ipv4_addr")
  ind2("flags dynamic,timeout")
  ind2("timeout 6h")
  ind2("counter")
  ind("}")
  emit("")

  -- Accounting chain: forward hook, low priority; updates tracking set per packet
  ind("chain familydns_account {")
  ind2("type filter hook forward priority 1; policy accept;")
  ind2("update @mac_ip_tracking { ether saddr . ip daddr } counter")
  ind("}")
  emit("")

  -- #305: blocked-MAC set. The API precomputes which MACs should be blocked
  -- *right now* from pause / daily time limit / active schedule window and
  -- ships them in snapshot.blockedMacs. We just enforce it — no wall-clock
  -- evaluation here, no per-profile decision logic. The set is read by both
  -- the filter-drop chain and the block-page DNAT chain (#303).
  local blocked = snapshot.blockedMacs or {}
  ind("set blocked_macs {")
  ind2("type ether_addr")
  if #blocked > 0 then
    local macs = {}
    for i, b in ipairs(blocked) do macs[i] = b.mac end
    ind2("elements = { " .. table.concat(macs, ", ") .. " }")
  end
  ind("}")
  emit("")

  -- Block chain: drops forwarded traffic from any MAC in blocked_macs.
  -- HTTPS/443 and any non-port-80 traffic falls through here (no transparent
  -- MITM possible for TLS, so blocked HTTPS just dies). HTTP/80 is also
  -- caught here, but the prerouting nat chain below DNATs it first so the
  -- user lands on the block page instead of seeing a hung connection.
  ind("chain familydns_block {")
  ind2("type filter hook forward priority 0; policy accept;")
  if #blocked > 0 then
    ind2("ether saddr @blocked_macs drop")
  end
  ind("}")
  emit("")

  -- Block-page DNAT chain (#303): redirect HTTP/80 from blocked devices to
  -- the local uhttpd block page on 127.0.0.1:8081 so users see *why* their
  -- device is blocked instead of a hung connection. DNAT can't live in a
  -- filter chain (#297), so it lives in a dedicated nat-prerouting chain.
  -- inet tables require the family qualifier on dnat (`dnat ip to ...` for
  -- v4) — the bare `dnat to ...` form is what crashed the ruleset in #297.
  -- HTTPS/443 is intentionally not redirected: there's no way to MITM TLS
  -- transparently, so blocked HTTPS continues to drop in the filter chain.
  -- The chain is omitted entirely when nothing is blocked, to avoid an
  -- unconditional prerouting hook with no work to do.
  if #blocked > 0 then
    ind("chain familydns_block_nat {")
    ind2("type nat hook prerouting priority dstnat; policy accept;")
    ind2("ether saddr @blocked_macs tcp dport 80 dnat ip to 127.0.0.1:8081")
    ind("}")
    emit("")
  end

  -- #311: API-unreachable failover. When poll_age_seconds > 300 we collect
  -- every device MAC belonging to a profile whose failureMode == "closed"
  -- and emit a drop rule. failureMode == "open" profiles are left to keep
  -- enforcing the cached snapshot. We skip emission entirely when there
  -- are no MACs to drop (empty Closed profile, or no Closed profiles) so
  -- we don't ship a degenerate rule that matches nothing.
  --
  -- TODO(#323): also DNAT HTTP/80 for @failover_drop into the #303 block
  -- page so failover-cut HTTP requests land on the explanatory page rather
  -- than hanging. Currently this branch is drop-only.
  local poll_age = opts and opts.poll_age_seconds
  if poll_age and poll_age > 300 then
    local closed_profile_ids = {}
    for _, prof in ipairs(snapshot.profiles or {}) do
      if prof.failureMode == "closed" then
        closed_profile_ids[prof.id] = true
      end
    end
    local failover_macs = {}
    for _, dev in ipairs(snapshot.devices or {}) do
      if dev.profileId and closed_profile_ids[dev.profileId] then
        failover_macs[#failover_macs + 1] = dev.mac
      end
    end
    if #failover_macs > 0 then
      ind("set failover_drop {")
      ind2("type ether_addr")
      ind2("elements = { " .. table.concat(failover_macs, ", ") .. " }")
      ind("}")
      emit("")
      ind("chain familydns_failover {")
      ind2("type filter hook forward priority -1; policy accept;")
      ind2("ether saddr @failover_drop drop")
      ind("}")
      emit("")
    end
  end

  emit("}")
  emit("")

  return table.concat(out, "\n")
end

-- ---------------------------------------------------------------------------
-- render.update_shared(snapshot, nft_sets, blocked_macs, blocked_reason)
-- ---------------------------------------------------------------------------
-- Seeds nft_sets with empty tables for each siteLimits domain so that
-- conntrack.lua can attribute hostnames from the moment the agent starts.
-- Actual IPs are populated at runtime by dnsmasq --ipset= callbacks.
--
-- Also rebuilds blocked_macs / blocked_reason from snapshot.blockedMacs (#305)
-- so conntrack.lua can label connection_attempt events as blocked. nft already
-- drops these flows at the forward hook, but the conntrack -E -e NEW watcher
-- still sees the SYN_SENT entry and needs an independent signal to classify
-- it correctly — labeling purely by destination IP misses pause /
-- time_limit / schedule (every IP is blocked).
--
-- Both tables are mutated in place (shared refs held by conntrack.lua); we
-- clear stale entries first so a profile that un-pauses or a schedule window
-- that ends stops marking flows as blocked on the next poll.
function M.update_shared(snapshot, nft_sets, blocked_macs, blocked_reason)
  for _, prof in ipairs(snapshot.profiles or {}) do
    for _, sl in ipairs(prof.siteLimits or {}) do
      if not nft_sets[sl.domain] then
        nft_sets[sl.domain] = {}
      end
    end
  end

  if blocked_macs then
    for k in pairs(blocked_macs) do blocked_macs[k] = nil end
  end
  if blocked_reason then
    for k in pairs(blocked_reason) do blocked_reason[k] = nil end
  end

  for _, b in ipairs(snapshot.blockedMacs or {}) do
    if blocked_macs   then blocked_macs[b.mac]   = true end
    if blocked_reason then blocked_reason[b.mac] = b.reason end
  end
end

return M
