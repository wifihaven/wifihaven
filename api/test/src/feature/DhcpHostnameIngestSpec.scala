/**
 * #2927: the hostname a device advertises over DHCP is stored in `devices.dhcp_hostname` (V91) on
 * every `dhcp_lease` / `first_seen_mac` that carries one, apart from `devices.name`, so the
 * identify view (#2926) can show what the device calls itself even after an operator renames it.
 *
 * Through the real `POST /api/router/events` route on embedded Postgres.
 */
object DhcpHostnameIngestSpec
    extends ZIOSpec[TestDatabase.AllRepos & EmbeddedPostgres & Clock & Transactor[Task]] {

  override val bootstrap =
    TestDatabase.layer ++ TestLayers.withClock(Clock.TestClock.schoolDayAfternoon)

  private val cleanDb = TestDatabase.cleanAndMigrate

  private val macA     = MacAddress.unsafe("aa:bb:cc:00:00:0a")
  private val macB     = MacAddress.unsafe("aa:bb:cc:00:00:0b")
  private val roku     = MacAddress.unsafe("08:05:81:12:34:56")
  private val routerTs = "2026-05-07T14:01:13Z"

  private def buildRoutes =
    for {
      rRepo <- ZIO.service[RouterRepo]
      tRepo <- ZIO.service[TrafficReportRepo]
      tu    <- ZIO.service[TimeUsageRepo]
      dRepo <- ZIO.service[DeviceRepo]
      cRepo <- ZIO.service[ConnectionEventRepo]
      aRepo <- ZIO.service[AlertRepo]
      hsr   <- ZIO.service[HouseholdSettingsRepo]
      auth = new RouterAuthLive(rRepo)
    } yield ErrorBoundary.observe(
      RouterIngestRoutes.routes(auth, rRepo, tRepo, tu, dRepo, cRepo, aRepo, hsr),
    )

  private def lease(
      kind: String,
      mac: MacAddress,
      hostname: Option[String],
      ts: String = routerTs,
  ) =
    RouterEvent(
      kind,
      mac = Some(mac),
      ip = Some(IpAddress.unsafe("192.168.1.60")),
      hostname = hostname.map(Hostname.unsafe),
      ts = ts,
    )

  private def send(routes: Routes[Any, Response], rid: RouterId, token: String, evs: RouterEvent*) =
    routes
      .runZIO(
        Request
          .post(
            URL.decode("/api/router/events").toOption.get,
            Body.fromString(RouterEventsRequest(rid, evs.toList).toJson),
          )
          .addHeader(Header.ContentType(MediaType.application.json))
          .addHeader(Header.Authorization.Bearer(token)),
      )
      .flatMap(r =>
        ZIO.when(r.status != Status.Ok)(ZIO.fail(new RuntimeException(s"ingest ${r.status}"))),
      )

  private def dhcpOf(mac: MacAddress, hh: HouseholdId) =
    ZIO.serviceWithZIO[DeviceRepo](_.discoveryInHousehold(mac, hh)).map(_.flatMap(_.dhcpHostname))

  def spec = suite("DHCP hostname ingest (#2927)")(
    test("a first_seen_mac with a hostname stores it on the new device row") {
      for {
        _      <- cleanDb
        two    <- TestLayers.seedTwoHouseholds(macA, macB)
        routes <- buildRoutes
        _      <- send(
          routes,
          two.routerIdA,
          two.tokenA,
          lease("first_seen_mac", roku, Some("Roku-Ultra")),
        )
        stored <- dhcpOf(roku, two.hhA)
        device <- ZIO.serviceWithZIO[DeviceRepo](_.findByMacInHousehold(roku, two.hhA))
      } yield assertTrue(stored.contains("roku-ultra")) && assertTrue(
        device.exists(_.name == "roku-ultra"),
      )
    },
    test("a later lease with a different hostname replaces it; the name keeps its first value") {
      for {
        _      <- cleanDb
        two    <- TestLayers.seedTwoHouseholds(macA, macB)
        routes <- buildRoutes
        _      <- send(
          routes,
          two.routerIdA,
          two.tokenA,
          lease("first_seen_mac", roku, Some("Roku-Ultra")),
        )
        before <- dhcpOf(roku, two.hhA)
        _      <- send(
          routes,
          two.routerIdA,
          two.tokenA,
          lease("dhcp_lease", roku, Some("Living-Room-TV")),
        )
        after  <- dhcpOf(roku, two.hhA)
        device <- ZIO.serviceWithZIO[DeviceRepo](_.findByMacInHousehold(roku, two.hhA))
      } yield assertTrue(before.contains("roku-ultra")) &&
        assertTrue(after.contains("living-room-tv")) &&
        // not a placeholder, so renameIfAutoGenerated leaves the name alone
        assertTrue(device.exists(_.name == "roku-ultra"))
    },
    test("a lease without a hostname leaves the stored hostname as it is") {
      for {
        _      <- cleanDb
        two    <- TestLayers.seedTwoHouseholds(macA, macB)
        routes <- buildRoutes
        _      <- send(
          routes,
          two.routerIdA,
          two.tokenA,
          lease("first_seen_mac", roku, Some("Roku-Ultra")),
        )
        _      <- send(routes, two.routerIdA, two.tokenA, lease("dhcp_lease", roku, None))
        after  <- dhcpOf(roku, two.hhA)
      } yield assertTrue(after.contains("roku-ultra"))
    },
    test("a device that never sent a hostname has none stored, and keeps its placeholder name") {
      for {
        _      <- cleanDb
        two    <- TestLayers.seedTwoHouseholds(macA, macB)
        routes <- buildRoutes
        _      <- send(routes, two.routerIdA, two.tokenA, lease("first_seen_mac", roku, None))
        disc   <- ZIO.serviceWithZIO[DeviceRepo](_.discoveryInHousehold(roku, two.hhA))
      } yield
      // liveness: the row exists, so the None below is the column, not a missing device
      assertTrue(disc.isDefined) && assertTrue(disc.flatMap(_.dhcpHostname).isEmpty)
    },
    test("an operator rename does not touch the stored hostname") {
      for {
        _       <- cleanDb
        two     <- TestLayers.seedTwoHouseholds(macA, macB)
        routes  <- buildRoutes
        dRepo   <- ZIO.service[DeviceRepo]
        _       <- send(
          routes,
          two.routerIdA,
          two.tokenA,
          lease("first_seen_mac", roku, Some("Roku-Ultra")),
        )
        dev     <- dRepo
          .findByMacInHousehold(roku, two.hhA)
          .someOrFail(new RuntimeException("no device"))
        _       <- dRepo.patch(two.hhA, dev.id, "Den TV", None, None, None)
        renamed <- dRepo.findByMacInHousehold(roku, two.hhA)
        after   <- dhcpOf(roku, two.hhA)
      } yield assertTrue(renamed.exists(_.name == "Den TV")) && assertTrue(
        after.contains("roku-ultra"),
      )
    },
    test("a lease in one household leaves the same MAC's row in another household unchanged") {
      for {
        _      <- cleanDb
        two    <- TestLayers.seedTwoHouseholds(macA, macB)
        routes <- buildRoutes
        _ <- send(routes, two.routerIdB, two.tokenB, lease("first_seen_mac", roku, Some("B-Roku")))
        _ <- send(routes, two.routerIdA, two.tokenA, lease("first_seen_mac", roku, Some("A-Roku")))
        inA <- dhcpOf(roku, two.hhA)
        inB <- dhcpOf(roku, two.hhB)
      } yield assertTrue(inA.contains("a-roku")) && assertTrue(inB.contains("b-roku"))
    },
  ) @@ TestAspect.sequential
}
