#!/usr/bin/env bash
# #2926: regenerate api/resources/oui/ma-l.tsv from the IEEE MA-L (24-bit OUI) public registry.
#
# The API never calls IEEE at runtime — the vendor lookup reads the bundled TSV (`MacVendor`), the
# same repo-authored-catalog stance as app templates and blocklists (#2535). Run this by hand when
# the table is stale and commit the result; the diff is the review surface.
#
# Usage: scripts/refresh-oui.sh [path-to-downloaded-oui.csv]
#   With no argument the CSV is fetched from IEEE. (IEEE's WAF rejects browser-like user agents;
#   plain curl works.)
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$repo_root/api/resources/oui/ma-l.tsv"
src_url="https://standards-oui.ieee.org/oui/oui.csv"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

if [[ $# -ge 1 ]]; then
  cp "$1" "$tmp/oui.csv"
else
  curl -sSfL -o "$tmp/oui.csv" "$src_url"
fi

mkdir -p "$(dirname "$out")"
python3 -I - "$tmp/oui.csv" "$out" "$src_url" <<'PY'
import csv, datetime, re, sys

src, out, url = sys.argv[1], sys.argv[2], sys.argv[3]
rows = {}
with open(src, newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r.get("Registry") != "MA-L":
            continue
        prefix = r["Assignment"].strip().upper()
        if not re.fullmatch(r"[0-9A-F]{6}", prefix):
            continue
        # Tabs/newlines would break the one-line-per-prefix format.
        name = " ".join(r["Organization Name"].split())
        if name:
            rows[prefix] = name
if len(rows) < 10000:
    sys.exit(f"refusing to write: only {len(rows)} MA-L rows parsed (expected ~38k)")
with open(out, "w", encoding="utf-8") as f:
    f.write(f"# IEEE MA-L registry, generated by scripts/refresh-oui.sh from {url}\n")
    f.write(f"# fetched {datetime.date.today().isoformat()}; {len(rows)} prefixes. Format: PREFIX<TAB>Organization\n")
    for prefix in sorted(rows):
        f.write(f"{prefix}\t{rows[prefix]}\n")
print(f"wrote {len(rows)} prefixes to {out}")
PY
